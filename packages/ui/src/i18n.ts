function normalize(tag: string | undefined | null): string {
  const base = (tag ?? '').toLowerCase().split('-')[0];
  return base === 'en' || dicts[base] ? base : '';
}

let current = (() => {
  try {
    const saved = normalize(localStorage.getItem('ludin.lang'));
    if (saved) return saved;
  } catch { /* ignore */ }
  return normalize((boot.theme as any)?.language) || normalize(navigator.language) || 'en';
})();

let notify: (() => void) | null = null;

/** The App subscribes once; a language change re-renders the whole tree. */
export function onLangChange(fn: () => void) {
  notify = fn;
}

export function getLang(): string {
  return current;
}

export function setLang(lang: string) {
  current = normalize(lang) || 'en';
  try { localStorage.setItem('ludin.lang', current); } catch { /* ignore */ }
  notify?.();
}

export function t(key: MsgKey, params?: Record<string, string | number>): string {
  let s = dicts[current]?.[key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}
